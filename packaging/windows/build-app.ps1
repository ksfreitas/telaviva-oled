<#
.SYNOPSIS
Builds the Windows app and assembles the unpackaged distribution folder.

.DESCRIPTION
Output layout under OutDir (default dist\TelaVivaOLED at the repository root):

  TelaViva.exe                         app host (self-contained WinUI 3, hybrid CRT)
  telaviva_core.dll                    Rust core C ABI
  telaviva_inference.dll               Rust inference C ABI
  onnxruntime.dll                      DirectML build of ONNX Runtime 1.20.1, required
  Microsoft.* runtime files, .pri, resource files, Assets\
  models\face_detection_retinaface_mb025.onnx
  models\manifest.toml
  selftest-face.bgra                   DirectML self-test frame, generated by tools\windows\make-selftest-frame.ps1
  licenses\LICENSE and the repository licenses\ folder
  VERSION                              release version, read by the installer
  .telaviva-dist                       marker; OutDir is only cleared when it is present

Import libraries, PDBs, object files and tests.exe are left out. The marker is
written before any copy, so an interrupted run can still be cleared by the next one.

Unless -NoZip is given, dist\TelaVivaOLED-<version>-win-x64.zip is also written. Its
entries sit at the root: the folder content above, then Install-TelaVivaOLED.ps1,
Uninstall-TelaVivaOLED.ps1 and README.md from packaging\windows.

.PARAMETER Configuration
Release (default) or Debug.

.PARAMETER OutDir
Destination folder. Empty means dist\TelaVivaOLED under the repository root.
Relative paths resolve from the repository root.

.PARAMETER NoZip
Write the folder only. By default the release zip is also written next to OutDir.

.PARAMETER KeepAllComponents
Keep the Windows App SDK files that the unused-component step would otherwise remove.
#>
[CmdletBinding()]
param(
    [ValidateSet('Release', 'Debug')]
    [string]$Configuration = 'Release',

    [string]$OutDir = '',

    # A switch, not [bool]: powershell.exe -File passes -Name:$false as the string '$false', which a [bool] rejects.
    [switch]$NoZip,

    [switch]$KeepAllComponents
)

$ErrorActionPreference = 'Stop'

function Fail {
    param([string]$Message)
    [Console]::Error.WriteLine("ERROR: $Message")
    exit 1
}

function Copy-RequiredFile {
    param(
        [string]$Source,
        [string]$Destination
    )
    if (-not (Test-Path -LiteralPath $Source -PathType Leaf)) { Fail "Required file is missing: $Source" }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Destination) | Out-Null
    Copy-Item -LiteralPath $Source -Destination $Destination -Force
}

# This script lives in packaging\windows, so the repository root is two levels up.
$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))

if ([string]::IsNullOrEmpty($OutDir)) {
    $OutDir = Join-Path $repoRoot 'dist\TelaVivaOLED'
}
elseif (-not [System.IO.Path]::IsPathRooted($OutDir)) {
    $OutDir = Join-Path $repoRoot $OutDir
}
$OutDir = [System.IO.Path]::GetFullPath($OutDir)
if ($OutDir -eq $repoRoot) { Fail 'OutDir must not be the repository root.' }

$marker = '.telaviva-dist'

# The release version comes from the core crate, because the workspace has no shared version key.
$versionManifest = Join-Path $repoRoot 'crates\telaviva-core\Cargo.toml'
if (-not (Test-Path -LiteralPath $versionManifest -PathType Leaf)) { Fail "Version manifest is missing: $versionManifest" }
$version = ''
foreach ($line in Get-Content -LiteralPath $versionManifest) {
    if ($line -match '^version\s*=\s*"([^"]+)"') {
        $version = $Matches[1]
        break
    }
}
if ([string]::IsNullOrEmpty($version)) { Fail "No version key found in $versionManifest." }

# Step 1: Rust DLLs. Exit codes from child processes are checked explicitly.
$rustScript = Join-Path $repoRoot 'tools\windows\build-rust-dlls.ps1'
Write-Host "> build-rust-dlls.ps1 -Configuration $Configuration"
& powershell.exe -NoProfile -ExecutionPolicy Bypass -File $rustScript -Configuration $Configuration
if ($LASTEXITCODE -ne 0) { Fail "build-rust-dlls.ps1 failed with exit code $LASTEXITCODE." }

# Step 2: MSBuild, located through vswhere because it is not on PATH by default.
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (-not (Test-Path -LiteralPath $vswhere -PathType Leaf)) {
    Fail "vswhere.exe not found at $vswhere. Install Visual Studio 2022 with the C++ and WinUI tooling."
}
$vsPath = & $vswhere -latest -products '*' -requires Microsoft.Component.MSBuild -property installationPath
if ($LASTEXITCODE -ne 0) { Fail "vswhere failed with exit code $LASTEXITCODE." }
$vsPath = @($vsPath) | Select-Object -First 1
if ([string]::IsNullOrEmpty($vsPath)) { Fail 'No Visual Studio installation with MSBuild was found.' }
$msbuild = Join-Path $vsPath 'MSBuild\Current\Bin\MSBuild.exe'
if (-not (Test-Path -LiteralPath $msbuild -PathType Leaf)) { Fail "MSBuild not found: $msbuild" }

$sln = Join-Path $repoRoot 'native\windows\TelaViva.sln'
Write-Host "> msbuild TelaViva.sln /restore /p:Platform=x64 /p:Configuration=$Configuration"
& $msbuild $sln /restore /nr:false '/p:Platform=x64' "/p:Configuration=$Configuration"
if ($LASTEXITCODE -ne 0) { Fail "msbuild failed with exit code $LASTEXITCODE." }

# Step 3: Collect the app output and the Rust DLLs built in step 1.
$buildDir = Join-Path $repoRoot "native\windows\build\x64\$Configuration"
$rustDir = Join-Path $repoRoot 'native\windows\build\rust'
if (-not (Test-Path -LiteralPath (Join-Path $buildDir 'TelaViva.exe') -PathType Leaf)) {
    Fail "TelaViva.exe was not produced in $buildDir."
}

# Step 4: Prepare OutDir. Only a folder created by this script is cleared.
if (Test-Path -LiteralPath $OutDir) {
    $existing = @(Get-ChildItem -LiteralPath $OutDir -Force)
    $hasMarker = Test-Path -LiteralPath (Join-Path $OutDir $marker) -PathType Leaf
    if ($existing.Count -gt 0 -and -not $hasMarker) {
        Fail "Refusing to clear ${OutDir}: it is not empty and has no $marker marker. Choose an empty folder."
    }
    Remove-Item -LiteralPath $OutDir -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
Set-Content -LiteralPath (Join-Path $OutDir $marker) -Value 'Written by packaging/windows/build-app.ps1.' -Encoding ASCII

# Step 5: App files. Symbols, import libraries, object files and the test host stay in the build folder.
$excludedExtensions = @('.pdb', '.lib', '.exp', '.obj', '.ilk', '.iobj', '.ipdb', '.idb', '.tlog', '.log')
$excludedNames = @('tests.exe')
$appFiles = Get-ChildItem -LiteralPath $buildDir -Recurse -File |
    Where-Object {
        ($excludedExtensions -notcontains $_.Extension.ToLowerInvariant()) -and
        ($excludedNames -notcontains $_.Name.ToLowerInvariant())
    }
foreach ($file in $appFiles) {
    $relative = $file.FullName.Substring($buildDir.Length).TrimStart('\')
    $destination = Join-Path $OutDir $relative
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
    Copy-Item -LiteralPath $file.FullName -Destination $destination -Force
}

# The Rust DLLs come from build\rust, so the fresh copies win over anything in the build folder.
foreach ($dll in @('telaviva_core.dll', 'telaviva_inference.dll')) {
    Copy-RequiredFile -Source (Join-Path $rustDir $dll) -Destination (Join-Path $OutDir $dll)
}

if (-not (Test-Path -LiteralPath (Join-Path $OutDir 'Assets') -PathType Container)) {
    Write-Warning 'Assets folder not found in the build output; check the WinUI content items.'
}

# Step 6: Model and manifest. The model is the pinned RetinaFace MobileNet0.25 file; the manifest records its hashes.
$modelsDir = Join-Path $OutDir 'models'
Copy-RequiredFile -Source (Join-Path $repoRoot 'assets\model\face_detection_retinaface_mb025.onnx') -Destination (Join-Path $modelsDir 'face_detection_retinaface_mb025.onnx')
Copy-RequiredFile -Source (Join-Path $repoRoot 'assets\model\manifest.toml') -Destination (Join-Path $modelsDir 'manifest.toml')

# Step 6b: DirectML self-test frame, generated on demand from the CC0 fixture.
# It sits next to TelaViva.exe, where the app looks for it.
$selftestScript = Join-Path $repoRoot 'tools\windows\make-selftest-frame.ps1'
$selftestFrame = Join-Path $repoRoot 'native\windows\build\selftest\selftest-face.bgra'
Write-Host "> make-selftest-frame.ps1"
& powershell.exe -NoProfile -ExecutionPolicy Bypass -File $selftestScript
if ($LASTEXITCODE -ne 0) { Fail "make-selftest-frame.ps1 failed with exit code $LASTEXITCODE; the self-test frame is required for the package." }
Copy-RequiredFile -Source $selftestFrame -Destination (Join-Path $OutDir 'selftest-face.bgra')

# Step 7: Licenses.
$licensesDir = Join-Path $OutDir 'licenses'
Copy-RequiredFile -Source (Join-Path $repoRoot 'LICENSE') -Destination (Join-Path $licensesDir 'LICENSE')
$licensesSource = Join-Path $repoRoot 'licenses'
if (-not (Test-Path -LiteralPath $licensesSource -PathType Container)) { Fail "Licenses folder is missing: $licensesSource" }
New-Item -ItemType Directory -Force -Path $licensesDir | Out-Null
Copy-Item -LiteralPath (Join-Path $licensesSource '*') -Destination $licensesDir -Recurse -Force
# The package ships RetinaFace only, so the YuNet license is removed from the package after the copy.
$yunetLicense = Join-Path (Join-Path $licensesDir 'inference') 'YUNET-LICENSE'
if (Test-Path -LiteralPath $yunetLicense -PathType Leaf) { Remove-Item -LiteralPath $yunetLicense -Force }

# Step 8: ONNX Runtime. The package ships only the DirectML build of ONNX Runtime 1.20.1, the one pinned as
# [runtime.windows-x64.directml] in assets\model\manifest.toml, copied under the name onnxruntime.dll.
# The file is required: Install-TelaVivaOLED.ps1 installs it, so a missing runtime stops the build.
$ortSource = Join-Path $repoRoot 'tools\inference\runtime\windows-x64-directml\onnxruntime.dll'
if (-not (Test-Path -LiteralPath $ortSource -PathType Leaf)) {
    Fail "The DirectML ONNX Runtime is missing: $ortSource. Run tools\inference\fetch-windows-runtime.ps1 -Variant directml."
}
Copy-Item -LiteralPath $ortSource -Destination (Join-Path $OutDir 'onnxruntime.dll') -Force

# Step 8b: Version file for the installer, and a check that the license file made it into the package.
Set-Content -LiteralPath (Join-Path $OutDir 'VERSION') -Value $version -Encoding ASCII
if (-not (Test-Path -LiteralPath (Join-Path $licensesDir 'LICENSE') -PathType Leaf)) { Fail 'licenses\LICENSE is missing from the package.' }

# Step 8c: Remove Windows App SDK files the app never loads. The list is explicit, so any new runtime
# file stays until someone decides on it. DirectML.dll is never redistributed: a copy next to the app
# would shadow the OS DirectML that ONNX Runtime uses. The ONNX Runtime and core/inference DLLs are kept.
$unusedComponents = @(
    'DirectML.dll',
    'Microsoft.Windows.AI.*',
    'Microsoft.Windows.Internal.AI.*',
    'Microsoft.Windows.Vision.winmd',
    'Microsoft.Windows.VisionInternal.winmd',
    'Microsoft.Windows.Internal.Vision.winmd',
    'Microsoft.Windows.SemanticSearch*.winmd',
    'Microsoft.Windows.SemanticSearchInternal.winmd',
    'Microsoft.Windows.Internal.SemanticSearch.winmd',
    'Microsoft.Windows.Private.Workloads.*',
    'Microsoft.Windows.Workloads.winmd',
    'Microsoft.Windows.ImageCreationInternal.winmd',
    'Microsoft.Windows.Internal.ImageCreation.winmd',
    'Microsoft.Graphics.Imaging*.winmd',
    'Microsoft.Graphics.ImagingInternal*.winmd',
    'Microsoft.Graphics.Internal.Imaging.winmd'
)
if ($KeepAllComponents) {
    Write-Host 'Keeping all Windows App SDK files (-KeepAllComponents).'
}
else {
    $protectedNames = @('onnxruntime.dll', 'telaviva_core.dll', 'telaviva_inference.dll')
    $removeFiles = @()
    foreach ($file in @(Get-ChildItem -LiteralPath $OutDir -File -Force)) {
        if ($protectedNames -contains $file.Name) { continue }
        if ($file.Name -like 'telaviva_*') { continue }
        foreach ($pattern in $unusedComponents) {
            if ($file.Name -like $pattern) {
                $removeFiles += $file
                break
            }
        }
    }
    if ($removeFiles.Count -eq 0) {
        Fail 'The unused-component list matched no file in the package root; the Windows App SDK layout may have changed. Review $unusedComponents in build-app.ps1.'
    }
    $removedBytes = [long](($removeFiles | Measure-Object -Property Length -Sum).Sum)
    foreach ($file in $removeFiles) {
        Remove-Item -LiteralPath $file.FullName -Force
        Write-Host "  removed $($file.Name)"
    }
    Write-Host ('Removed {0} unused Windows App SDK files, {1:N1} MB ({2:N0} bytes)' -f $removeFiles.Count, ($removedBytes / 1MB), $removedBytes)
}

# Step 9: Summary.
$summaryFiles = @(Get-ChildItem -LiteralPath $OutDir -Recurse -File -Force |
    Where-Object { $_.Name -ne $marker })
$totalBytes = [long](($summaryFiles | Measure-Object -Property Length -Sum).Sum)
Write-Host ''
Write-Host "Assembled: $OutDir"
Write-Host ('Files: {0}' -f $summaryFiles.Count)
Write-Host ('Size:  {0:N1} MB ({1:N0} bytes)' -f ($totalBytes / 1MB), $totalBytes)

# Step 10: Release zip. Entries sit at the zip root, sorted ordinally with forward slashes and a fixed
# timestamp, so the same inputs give the same archive. The marker file is not shipped.
if (-not $NoZip) {
    $zipInputs = @(
        (Join-Path $PSScriptRoot 'Install-TelaVivaOLED.ps1'),
        (Join-Path $PSScriptRoot 'Uninstall-TelaVivaOLED.ps1'),
        (Join-Path $PSScriptRoot 'README.md')
    )
    foreach ($zipInput in $zipInputs) {
        if (-not (Test-Path -LiteralPath $zipInput -PathType Leaf)) { Fail "Zip input is missing: $zipInput" }
    }

    $entryMap = @{}
    foreach ($file in @(Get-ChildItem -LiteralPath $OutDir -Recurse -File -Force | Where-Object { $_.Name -ne $marker })) {
        $entryName = $file.FullName.Substring($OutDir.Length).TrimStart('\').Replace('\', '/')
        $entryMap[$entryName] = $file.FullName
    }
    foreach ($zipInput in $zipInputs) {
        $entryName = Split-Path -Leaf $zipInput
        if ($entryMap.ContainsKey($entryName)) { Fail "Zip entry name is used twice: $entryName" }
        $entryMap[$entryName] = $zipInput
    }
    $entryNames = [string[]]@($entryMap.Keys)
    [Array]::Sort($entryNames, [StringComparer]::Ordinal)

    $zipPath = Join-Path (Split-Path -Parent $OutDir) "TelaVivaOLED-$version-win-x64.zip"
    if (Test-Path -LiteralPath $zipPath) { Remove-Item -LiteralPath $zipPath -Force }

    Add-Type -AssemblyName System.IO.Compression
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $entryTime = New-Object System.DateTimeOffset -ArgumentList 1980, 1, 2, 0, 0, 0, ([TimeSpan]::Zero)
    $archive = [System.IO.Compression.ZipFile]::Open($zipPath, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
        foreach ($entryName in $entryNames) {
            $entry = $archive.CreateEntry($entryName, [System.IO.Compression.CompressionLevel]::Optimal)
            $entry.LastWriteTime = $entryTime
            $sourceStream = [System.IO.File]::OpenRead($entryMap[$entryName])
            try {
                $targetStream = $entry.Open()
                try { $sourceStream.CopyTo($targetStream) } finally { $targetStream.Dispose() }
            }
            finally { $sourceStream.Dispose() }
        }
    }
    finally { $archive.Dispose() }

    $zipSize = (Get-Item -LiteralPath $zipPath).Length
    $zipHash = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash
    Write-Host ''
    Write-Host "Zip:     $zipPath"
    Write-Host ('Zip size: {0:N1} MB ({1:N0} bytes), {2} entries' -f ($zipSize / 1MB), $zipSize, $entryNames.Count)
    Write-Host "SHA-256: $zipHash"
}
exit 0
